/* 16bit風のドット絵（コードで描くオリジナルの仮素材）
 *
 * - 小さなキャンバスに整数座標の四角だけで描き（にじまない）、最後に濃い輪郭線を自動で付ける。
 * - 描画側は最近傍で拡大する（1ドット = PIX 論理ドット）。
 * - すべて右向きで描く。魔王軍は描画時に左右反転して左を向く。
 * - 正式な素材（docs/ART_SPEC.md）が届いたら js/data/skin.js の sprites に登録すれば、そちらが優先される。
 */

export const PIX = 2.5; // 1ドットの大きさ（論理ドット）。建物・背景は backdrop.js の BG_PIX（2）
const OUTLINE = [26, 14, 38];

function canvas(w, h) {
  if (typeof OffscreenCanvas !== 'undefined') return new OffscreenCanvas(w, h);
  const c = document.createElement('canvas'); c.width = w; c.height = h; return c;
}

// 描画の道具（整数の四角だけで描く）
function tools(ctx) {
  const R = (x, y, w, h, c) => { ctx.fillStyle = c; ctx.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h)); };
  const E = (cx, cy, rx, ry, c) => { // 塗りの楕円（行ごとの四角）
    ctx.fillStyle = c;
    for (let y = -ry; y <= ry; y++) {
      const t = 1 - (y * y) / ((ry + 0.5) * (ry + 0.5));
      if (t < 0) continue;
      const hw = Math.round(rx * Math.sqrt(t));
      ctx.fillRect(Math.round(cx - hw), Math.round(cy + y), hw * 2 + 1, 1);
    }
  };
  const C = (cx, cy, r, c) => E(cx, cy, r, r, c);
  const L = (x0, y0, x1, y1, c, w = 1) => { // 線（ドットを並べる）
    ctx.fillStyle = c;
    const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) || 1;
    for (let i = 0; i <= n; i++) ctx.fillRect(Math.round(x0 + (x1 - x0) * i / n), Math.round(y0 + (y1 - y0) * i / n), w, w);
  };
  const P = (pts, c) => { // 多角形（行ごとに塗る）
    ctx.fillStyle = c;
    const ys = pts.map((p) => p[1]); const y0 = Math.floor(Math.min(...ys)); const y1 = Math.ceil(Math.max(...ys));
    for (let y = y0; y <= y1; y++) {
      const xs = [];
      for (let i = 0; i < pts.length; i++) {
        const [ax, ay] = pts[i]; const [bx, by] = pts[(i + 1) % pts.length];
        if ((ay <= y + 0.5 && by > y + 0.5) || (by <= y + 0.5 && ay > y + 0.5)) xs.push(ax + (y + 0.5 - ay) * (bx - ax) / (by - ay));
      }
      xs.sort((a, b) => a - b);
      for (let i = 0; i + 1 < xs.length; i += 2) ctx.fillRect(Math.round(xs[i]), y, Math.max(1, Math.round(xs[i + 1]) - Math.round(xs[i])), 1);
    }
  };
  // 目（白目と黒目。右向き）
  const EYE = (x, y, s = 2, pupil = '#1a0f24') => { R(x, y, s, s + 1, '#ffffff'); R(x + s - 1, y + 1, 1, s, pupil); };
  return { R, E, C, L, P, EYE };
}

// 輪郭線（透明なところで、となりが不透明なら輪郭の色）
function outline(c, color = OUTLINE) {
  const ctx = c.getContext('2d');
  const { width: w, height: h } = c;
  const img = ctx.getImageData(0, 0, w, h); const d = img.data;
  const solid = (x, y) => x >= 0 && y >= 0 && x < w && y < h && d[(y * w + x) * 4 + 3] > 0;
  const add = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (solid(x, y)) continue;
    if (solid(x - 1, y) || solid(x + 1, y) || solid(x, y - 1) || solid(x, y + 1)) add.push(y * w + x);
  }
  for (const i of add) { d[i * 4] = color[0]; d[i * 4 + 1] = color[1]; d[i * 4 + 2] = color[2]; d[i * 4 + 3] = 255; }
  ctx.putImageData(img, 0, 0);
}

// 白いシルエット（被弾の点滅用）
function whiteOf(c) {
  const w = canvas(c.width, c.height); const x = w.getContext('2d');
  x.drawImage(c, 0, 0); x.globalCompositeOperation = 'source-in'; x.fillStyle = '#ffffff'; x.fillRect(0, 0, c.width, c.height);
  return w;
}

function build(w, h, draw) {
  const c = canvas(w + 2, h + 2);
  const ctx = c.getContext('2d');
  ctx.translate(1, 1);
  draw(tools(ctx), ctx);
  outline(c);
  return { img: c, white: whiteOf(c), w: w + 2, h: h + 2, footY: h + 1 };
}


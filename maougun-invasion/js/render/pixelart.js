// ---------------------------------------------------------------- 生成とキャッシュ
const cache = new Map();
export function unitSprite(key) {
  if (cache.has(key)) return cache.get(key);
  const def = ART[key] || HUMAN_ART[key];
  if (!def || typeof document === 'undefined') { cache.set(key, null); return null; }
  const [w, h, draw] = def;
  const s = build(w, h, draw);
  cache.set(key, s);
  return s;
}
